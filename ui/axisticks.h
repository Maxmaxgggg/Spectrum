#pragma once

#include <cmath>

// Шаг между подписями оси X: сколько столбцов спектра приходится на одну
// подпись. Ноль означает, что подписи строить не надо.
//
// Вынесено отдельной функцией без единой зависимости от Qt намеренно: именно
// здесь приложение падало, когда график убирали вправо до упора. Сплиттер
// схлопывает виджет в нулевую ширину, деление даёт бесконечность, а int от
// бесконечности — INT_MIN. Цикл построения подписей с отрицательным шагом
// не заканчивается и набивает массивы точек, пока не кончится память.
//
// Так функцию можно прогнать тестом, не поднимая ни окна, ни QCustomPlot.
inline int axisLabelStep(int size, int width, double spacingPx)
{
    // Схлопнутый график или пустой спектр — подписывать нечего.
    if (size <= 0 || width <= 0 || spacingPx <= 0.0)
        return 0;

    const double pixelsPerBar = double(width) / double(size);
    const double raw = std::ceil(spacingPx / pixelsPerBar);

    // Границы обязательны с обеих сторон: при ширине в считаные пиксели
    // формула даёт десятки тысяч, при огромной — ноль.
    if (!(raw >= 1.0))          // ложно и для NaN
        return 1;
    if (raw >= double(size))
        return size;

    return int(raw);
}
