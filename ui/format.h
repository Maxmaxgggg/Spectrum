#pragma once

#include <QObject>
#include <QString>
#include <QtGlobal>

// Форматирование величин, которые показываются во время расчёта.
//
// Вынесено из MainWindow: к окну это отношения не имеет, а разбор длительности
// на дни-часы-минуты был там скопирован дословно в двух местах, причём копии
// успели чуть разойтись в обработке нулевого случая.
namespace Format {

// Длительность словами: «2 д 3 ч 15 мин», «4 с».
// Пустой результат невозможен: при нуле возвращается «0 с».
QString duration(qint64 seconds);

// Оставшееся время. Отличается от duration тем, что секунды не показываются
// вовсе, а меньше минуты сворачивается в «Меньше минуты»: на расчётах в часы
// точность до секунды бессмысленна и только мельтешит.
QString remainingTime(int minutesTotal);

// Скорость перебора: «4,48 млрд слов/с».
QString speed(double wordsPerSecond);

// Число слов: «3,16 млрд». На этих задачах доходит до триллионов, поэтому
// без сокращения читать невозможно.
QString count(quint64 n);

// Разбивает число на разряды по три: «19222128» -> «19 222 128».
// Работает со строкой, а не с числом: у дуального расчёта компоненты спектра
// считаются в GMP и в quint64 не помещаются.
QString groupDigits(const QString& digits);

} // namespace Format
