#pragma once

#include <QVector>

// Какие интервалы обновления спектра имеет смысл предлагать при таком потолке.
//
// Потолок — сколько раз в секунду спектр физически успевает уйти в интерфейс.
// Он замеряется пробой и разнится в разы: спектр копируется с видеокарты не
// когда захочется, а на границе чанка, и длина чанка зависит от кода, сетки и
// пути расчёта. Замерено после кольца копий: широкий код 2000x50 даёт 6,9
// отправки в секунду, а матрица 336x96 — 54,6.
//
// Всё, что быстрее потолка, в списке настроек работать не будет: интервал
// пройдёт, а отправлять будет нечего. Такие пункты блокируются.
//
// Без единой зависимости от Qt-виджетов и CUDA намеренно: так это проверяется
// тестами, не поднимая ни окна, ни видеокарты.

// Успеет ли спектр обновляться так часто, как просит интервал.
inline bool intervalReachable(int intervalMs, double perSecond)
{
    // Ноль и отрицательные — не интервал. Потолок в ноль означает, что замера
    // нет или он ничего не поймал: тогда недостижимо всё.
    if (intervalMs <= 0)
        return false;
    if (!(perSecond > 0.0))     // ложно и для NaN
        return false;

    // Сравнение нестрогое: интервал ровно на потолке достижим. Потолок сам по
    // себе величина замеренная, с точностью до шума, и отсекать по нему строго
    // значило бы выкидывать пункт из-за сотой доли.
    return 1000.0 / double(intervalMs) <= perSecond;
}

// Самый частый из достижимых интервалов. Ноль — не подходит ни один.
//
// Нужен, чтобы перевести выбор, когда сохранённая настройка оказалась быстрее
// потолка: оставить её нельзя, а сбрасывать в самый медленный вариант обидно.
inline int fastestAllowed(const QVector<int>& intervalsMs, double perSecond)
{
    int best = 0;
    for (int ms : intervalsMs) {
        if (!intervalReachable(ms, perSecond))
            continue;
        if (best == 0 || ms < best)
            best = ms;
    }
    return best;
}
