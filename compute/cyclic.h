#pragma once

// Циклическая симметрия кода: сдвиг столбцов по кругу, переводящий код в
// себя. Есть у циклических кодов (БЧХ, Хэмминг, Голей в циклической форме) —
// сдвигаются все n столбцов — и у расширенных циклических: там общая
// проверка чётности стоит на месте, а по кругу идут остальные n − 1.
//
// Зачем. Вместе с каждым кодовым словом в коде лежат все его сдвиги — орбита,
// у них один вес. Случайному поиску (leon.h) достаточно поймать любое слово
// орбиты, остальные получаются сдвигом: попыток нужно во много раз меньше, а
// таблица хранит по одному представителю на орбиту — во столько же раз
// меньше памяти. Так поступают с квазициклическими кодами LDPC в работах
// Hirotomo, Mohri, Morii по вероятностному подсчёту низа спектра.
//
// Орбита. Сдвиги на t и на t + L совпадают (L — длина круга), поэтому
// различных сдвигов не больше L; ровно столько, если у слова нет периода.
// Слово с периодом p (сдвиг на p переводит его в себя) имеет орбиту из p
// слов, и p делит L.

#include <QtGlobal>

#include <vector>

namespace Cyclic {

// Сдвиг столбцов [start, start + length) по кругу: столбец start + j
// переходит в start + (j + 1) mod length. length == 0 — симметрии нет.
struct Symmetry
{
    int start  = 0;
    int length = 0;

    bool active() const { return length > 1; }
};

// Ищет у кода с порождающей матрицей rows x cols сдвиг всех столбцов, а если
// его нет — всех, кроме последнего или первого. Код переходит в себя, если
// сдвиг каждой строки матрицы лежит в коде. Нет ни того, ни другого —
// пустая симметрия.
Symmetry find(const quint64* matrix, int rows, int cols, int wordsPerRow);

// Слово, сдвинутое на shift позиций по кругу симметрии; столбцы вне круга —
// как были. out не должен совпадать с word.
void rotate(const quint64* word, int wordsPerRow, const Symmetry& symmetry, int shift, quint64* out);

// Представитель орбиты — один и тот же у всех её слов: наименьший (как
// массив 64-битных слов, с младшего) из сдвигов, ставящих единицу на начало
// круга. Таких сдвигов столько, сколько единиц на круге, а не L, — это
// дёшево. Возвращает размер орбиты. Слово без единиц на круге — само себе
// представитель, орбита из одного слова.
int canonical(const quint64* word, int wordsPerRow, const Symmetry& symmetry, quint64* out);

// Возможные размеры орбиты у слова с cyclicWeight единицами на круге: p
// делит L, и L / p делит cyclicWeight — на периоде единиц поровну.
std::vector<int> orbitSizes(const Symmetry& symmetry, int cyclicWeight);

} // namespace Cyclic
