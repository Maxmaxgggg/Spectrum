#pragma once

// Двоичные примитивные БЧХ-коды в узком смысле: минимальные многочлены над
// GF(2^m), порождающий многочлен и порождающая матрица в систематическом
// виде.
//
// Поле GF(2^m) задаётся примитивным многочленом из таблицы (7, 13, 23, 45,
// 103, 211, 435, 1021, 2011 восьмеричные — те же, что в справочниках, поэтому
// и минимальные многочлены совпадают с книжными). Минимальный многочлен
// α^i один и тот же для всего циклотомического класса {i, 2i, 4i, …} по
// модулю 2^m − 1; класс называется по наименьшему элементу — представителю.
// Представители нечётны (чётный i = 2j лежит в классе j).
//
// Код с первыми r представителями: g(x) — произведение их минимальных
// многочленов, корни g — все α^i, чей класс взят. Конструктивное расстояние
// δ — по границе БЧХ: наибольшее L с корнями α^1 … α^L, δ = L + 1,
// исправляется t = ⌊(δ−1)/2⌋ ошибок. n = 2^m − 1, k = n − deg g.
//
// Систематическая матрица: строка i — единичный вектор на позиции i и
// проверочная часть x^{n−k+i} mod g(x), коэффициенты от младшей степени к
// старшей (так же лежит БЧХ [63,51] в библиотеке Макса). Расширение
// добавляет справа бит чётности строки (n + 1, δ + 1); укорочение на s
// убирает первые s строк и первые s столбцов (n − s, k − s).

#include <QString>
#include <QStringList>

#include <cstdint>
#include <vector>

namespace Bch {

constexpr int MIN_M = 2;
constexpr int MAX_M = 10;

// Примитивный многочлен поля GF(2^m), биты — коэффициенты.
uint32_t primitivePolynomial(int m);

struct MinimalPolynomial
{
    int      exponent = 0;   // представитель класса, нечётный
    int      degree   = 0;   // размер класса
    uint32_t poly     = 0;   // коэффициенты битами, младшая степень — бит 0
    QString  octal;          // как в справочниках: 211, 217, …
};

// Минимальные многочлены поля по представителям, в порядке возрастания
// представителя. Первый — примитивный (α), он же m_1.
std::vector<MinimalPolynomial> minimalPolynomials(int m);

struct Code
{
    int         n = 0;
    int         k = 0;
    int         designedDistance = 0;   // δ по границе БЧХ (у расширенного — на единицу больше)
    int         corrects         = 0;   // t
    QString     generator;              // g(x) двоичной строкой, старшая степень слева
    QStringList rows;                   // порождающая матрица
};

// Код по m и числу взятых представителей (первые reps из minimalPolynomials).
// extend — приписать бит чётности; shorten — укоротить на столько символов.
// Пустой Code (n == 0), если параметры не дают кода: reps вне диапазона,
// shorten >= k.
Code build(int m, int reps, bool extend, int shorten);

// Только размеры, без матрицы — для показа n и k при наведении.
Code describe(int m, int reps, bool extend, int shorten);

} // namespace Bch
