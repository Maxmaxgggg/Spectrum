#pragma once

// Ядро случайного поиска по информационным множествам (Леон) — см.
// leon.h. Блок нитей = одна попытка: копия матрицы приводится к
// систематическому виду на случайном множестве (матрица в глобальной
// памяти — Гауссом четырёх русских: столбцы группами, таблица сумм
// опорных строк в разделяемой памяти; в разделяемой — по столбцу), потом
// блок перебирает комбинации до rowsPerTrial строк и слова веса не больше
// maxWeight выкладывает в общий буфер.
//
// Слова ловятся по многу раз (на 336x96 до веса 48 — по сотне раз каждое),
// и выкладывать каждую поимку хосту дорого: 10 ГБ копий и хост, разбирающий
// повторы дольше, чем видеокарта считает. Поэтому у ядра есть таблица уже
// виденных слов прямо в памяти видеокарты: 64-битный отпечаток слова,
// счётчик поимок и вес на ячейку, открытая адресация. Новое слово
// выкладывается хосту один раз, повтор лишь увеличивает счётчик. Счётчики
// хост читает для оценки Чао. Переполнять таблицу нельзя: при заполнении
// хост её удваивает (перекладка ядром); если памяти нет, слова без ячейки
// выкладываются хосту при каждой поимке, как без таблицы, — только поимки
// у них не считаются нигде, и в оценку Чао они не входят.
//
// Место в буфере занимается раньше, чем слово попадает в таблицу: если
// буфер переполнился и пачка пойдёт заново, слово, уже записанное в таблицу,
// но не доехавшее до хоста, потерялось бы.
//
// Два варианта одного ядра. Матрицы, что влезли, живут в разделяемой
// памяти блока (до 40 КБ — как обычно, дальше по опт-ину до предела
// устройства, см. leonSharedTier); остальные — в глобальной, у каждого
// блока свой кусок рабочего буфера. Второй вариант медленнее, но строки
// до 2048 бит ему по силам.

#include <cuda_runtime.h>

#include <cstddef>
#include <cstdint>

struct LeonLaunch
{
    const uint64_t* matrix       = nullptr;   // k x wordsPerRow, в глобальной памяти
    int             rows         = 0;
    int             cols         = 0;
    int             wordsPerRow  = 0;
    int             rowsPerTrial = 0;
    int             maxWeight    = 0;
    uint64_t        firstTrial   = 0;         // номер первой попытки — затравка
    int             trials       = 0;         // блоков в запуске
    uint64_t*       outWords     = nullptr;   // capacity x wordsPerRow
    unsigned*       outCount     = nullptr;   // сколько слов выложено (может превысить capacity)
    unsigned        capacity     = 0;
    // Таблица виденных слов; seenFp == nullptr — таблицы нет, выкладывается
    // каждая поимка. Ячеек seenMask + 1 (степень двойки).
    uint64_t*       seenFp       = nullptr;   // отпечаток, 0 — пусто
    unsigned*       seenHits     = nullptr;   // поимок
    uint16_t*       seenWeight   = nullptr;   // вес слова
    unsigned*       seenCount    = nullptr;   // занятых ячеек
    uint64_t        seenMask     = 0;
    // Рабочий буфер варианта с матрицей в глобальной памяти:
    // trials x rows x paddedWordCount(wordsPerRow) слов. Не нужен, если
    // матрица помещается в разделяемую память.
    uint64_t*       scratch      = nullptr;
    // Гаусс (ставит launchLeonTrials): ширина группы столбцов (1 — по
    // столбцу), с таблицей сумм опорных строк (четыре русских) или без
    // неё (прочие строки складываются прямо с опорными по своим битам —
    // столько же сложений, что по столбцу, но одним проходом и с четырьмя
    // барьерами на группу вместо двух на столбец), и до скольких строк
    // на лэйн опоры группы ищет один варп, а не весь блок.
    int             gaussGroup   = 0;
    bool            gaussTable   = false;
    int             searchRowsPerLane = 8;
    // Окно Штерна–Дюмера (см. Leon::trialStern): window > 0 — попытка
    // перебирает пары «до rowsPerTrial строк первой половины» × «до
    // rowsPerTrial второй» с равными ключами на окне. Список первой
    // половины (listA записей, цепочки по hashSlots головам) и список
    // найденных пар (pairCapacity, задаёт хост по профилю ключей) — в куске
    // рабочего буфера блока за копией матрицы; scratchWords — слов на блок
    // (leonScratchWords). Ставит launchLeonTrials всё, кроме window и
    // pairCapacity.
    int             window       = 0;
    unsigned        pairCapacity = 0;
    uint64_t        hashSlots    = 0;
    int             hashShift    = 0;         // 32 − log2(hashSlots)
    unsigned        listA        = 0;
    size_t          scratchWords = 0;
};

// Нитей в блоке: Гаусс идёт всем блоком по строкам, перебор — по
// комбинациям; сетка из настроек тут ни при чём. По этому числу считается
// и место в разделяемой памяти (leonSharedBytes).
constexpr int LEON_THREADS = 256;

// Слов в строке рабочей копии — paddedWordCount (wordvariants.h): число
// слов округляется вверх до одного из заготовленных вариантов ядра, хвост
// нулевой; ноль — строка длиннее, чем ядро умеет (MAX_BLOCKWORDS).

// Где живёт рабочая копия матрицы: 0 — в глобальной памяти (свой кусок
// рабочего буфера у блока), 1 — в разделяемой (до MAX_SHARED_BYTES),
// 2 — в разделяемой по опт-ину (до предела устройства, на Ampere 99 КБ;
// один блок на мультипроцессор — зато Гаусс и перебор не ходят в DRAM:
// у [961,676] попытка была 16 мс времени блока). window — окно
// Штерна–Дюмера: с ним в разделяемой памяти ещё ключи строк.
int leonSharedTier(int rows, int cols, int wordsPerRow, int window);

// true — матрица помещается в разделяемую память блока (любой ярус) и
// рабочий буфер в глобальной для неё не нужен.
bool leonFitsShared(int rows, int cols, int wordsPerRow);

// Слов рабочего буфера на блок: копия матрицы, если она не помещается в
// разделяемую память, и с окном Штерна–Дюмера — список первой половины
// (listA записей, головы цепочек hashSlots — вдвое больше списка, степень
// двойки) и список пар на pairCapacity записей.
size_t leonScratchWords(int rows, int cols, int wordsPerRow, int rowsPerTrial, int window,
                        unsigned pairCapacity, uint64_t* hashSlots = nullptr, unsigned* listA = nullptr);

// Разделяемой памяти на блок для этой матрицы (с учётом варианта).
size_t leonSharedBytes(int rows, int cols, int wordsPerRow);

// Бросает std::invalid_argument, если запуск не удался.
void launchLeonTrials(const LeonLaunch& launch, int threadsPerBlock, cudaStream_t stream);

// Сколько шагов пробирования делает ядро, прежде чем сдаться и выложить
// слово хосту. При заполнении не выше 0,6 это практически не случается.
constexpr int SEEN_PROBES = 64;

// Перекладка таблицы виденных слов в новую, вдвое большую: каждая занятая
// ячейка старой вставляется в новую с теми же счётчиком и весом.
void launchSeenRehash(const uint64_t* oldFp, const unsigned* oldHits, const uint16_t* oldWeight,
                      uint64_t oldCapacity,
                      uint64_t* newFp, unsigned* newHits, uint16_t* newWeight, uint64_t newMask,
                      cudaStream_t stream);
