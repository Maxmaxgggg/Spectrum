#pragma once

// Информационные множества для алгоритма Брауэра–Циммермана.
//
// Идея алгоритма. Приведём порождающую матрицу к систематическому виду на
// k столбцах: там у каждого кодового слова стоит его информационный вектор,
// и вес слова не меньше числа сложенных строк. Перебрав все комбинации до
// r строк такой матрицы, мы нашли все слова, у которых на этих k столбцах
// не больше r единиц.
//
// Одного множества мало: гарантия растёт как r, а цена как C(k, r). Берём m
// множеств, не пересекающихся по столбцам. Слово, не пойманное ни одним
// перебором до r строк, несёт не меньше r+1 единиц на каждом из них, а
// множества не пересекаются — итого вес не меньше m(r+1). Цена выросла в m
// раз по слагаемым, гарантия — в m раз по показателю.
//
// Когда непересекающиеся множества кончаются, следующее может пересекаться
// с прежними: тогда его вклад в гарантию — r+1 минус число общих столбцов.
//
// Правило единственности. Одно и то же слово находится перебором каждого
// множества, где у него не больше r единиц. Засчитывает его то множество,
// на котором единиц меньше всего; при равенстве — первое по порядку. Правило
// не зависит от глубины перебора, поэтому слои можно наращивать, продолжая
// сохранённый расчёт, а не начиная заново.
//
// Здесь только подготовка: поиск множеств, систематические матрицы и
// арифметика гарантии. Сам перебор делают обычные вычислительные пути —
// им достаточно матрицы, масок и номера множества.

#include <QStringList>
#include <QVector>
#include <QtGlobal>

#include <vector>

namespace InfoSets {

struct InfoSet
{
    // Опорные столбцы в порядке строк: строка i имеет единицу в columns[i]
    // и нули в остальных опорных столбцах.
    std::vector<int>     columns;
    // Те же столбцы битовой маской, слов столько же, сколько в строке.
    std::vector<quint64> mask;
    // Сколько столбцов уже заняты прежними множествами.
    int                  overlap = 0;
    // Матрица в систематическом виде на этих столбцах, k строк подряд.
    std::vector<quint64> rows;
};

// Упаковка строк матрицы в биты: столбец c — бит c%64 слова c/64.
std::vector<quint64> packRows(const QStringList& matrix, int& wordsPerRow);

// Приведение к систематическому виду. Опорные столбцы берутся из order по
// порядку: сначала те, что не заняты (avoid), потом занятые — каждый такой
// увеличивает overlap. Без avoid проверяется ровно заданный набор столбцов:
// так восстанавливается множество из сохранённого списка.
//
// Приведённая матрица определяется строками и опорными столбцами однозначно,
// поэтому восстановленная совпадает с найденной побитово. false — строки
// зависимы или столбцов не хватило.
bool systematize(const quint64* matrix, int rows, int cols, int wordsPerRow,
                 const std::vector<int>& order, const std::vector<quint64>* avoid,
                 InfoSet& out);

// Поиск множеств: жадно, одно за другим, каждое с наименьшим перекрытием из
// нескольких случайных порядков столбцов. Порядок решает: на структурной
// матрице проход слева направо забирает столбцы так, что на остатке ранга не
// хватает, а случайный находит непересекающееся множество. Останавливается,
// когда очередное множество целиком лежит в занятых столбцах.
//
// Детерминирован: тот же вход — те же множества. Пустой результат — матрица
// не полного ранга.
std::vector<InfoSet> find(const quint64* matrix, int rows, int cols, int wordsPerRow,
                          int maxSets);

// Восстановление множеств по сохранённым спискам столбцов. false — списки не
// подходят к матрице.
bool rebuild(const quint64* matrix, int rows, int cols, int wordsPerRow,
             const QVector<QVector<int>>& columns, std::vector<InfoSet>& out);

// Перекрытия по спискам столбцов: сколько столбцов множества j заняты
// множествами до него.
std::vector<int> overlapsOf(const QVector<QVector<int>>& columns);

// Граница гарантии: перебрав до r строк в каждом множестве, все слова веса
// меньше этого найдены. При r >= k перебрано всё, и граница — cols + 1.
int guaranteedBelow(const std::vector<int>& overlaps, int r, int rows, int cols);

// До скольких строк перебирать, чтобы все слова веса <= weight были найдены:
// наименьшее r с guaranteedBelow(r) > weight, не больше k.
int rowsForWeight(const std::vector<int>& overlaps, int weight, int rows, int cols);

// Сколько первых множеств взять под заданный вес. Лишнее множество не
// добавляет гарантии, а перебор стоит столько же — от него один вред.
// Возвращает число множеств с наименьшей общей ценой m * sum C(k, r), r <= R.
int setsForWeight(const std::vector<int>& overlaps, int weight, int rows, int cols);

} // namespace InfoSets
