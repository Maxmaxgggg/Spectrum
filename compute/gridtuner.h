#pragma once

#include <cuda_runtime.h>

#include <cstdint>

// Число блоков и нитей, с которым запускается ядро.
struct LaunchGrid
{
    int blocks  = 0;
    int threads = 0;

    bool isValid() const { return blocks > 0 && threads > 0; }
};

// Задание на подбор сетки.
//
// Матрица к этому моменту уже должна лежать на устройстве — в константной
// или в глобальной памяти, смотря по размеру. Подбор гоняет то же самое
// боевое ядро, что и расчёт, но пишет в отдельный буфер спектра, который
// потом выбрасывается: замер не имеет права повлиять на результат.
struct GridTuneTask
{
    // Ядро кода Грея вместо простого XOR.
    bool gray = false;

    int numOfCols   = 0;
    int numOfRows   = 0;
    int wordsPerRow = 0;

    // Число единиц в маске, на котором идёт замер. Для кода Грея не нужно:
    // он перебирает маски сплошь, без разбиения по весу.
    uint64_t numOfOnes = 0;
    // Сколько масок в этом слое (для Грея — всего). Замер не должен выйти
    // за границу: за ней ядро считает мусор.
    uint64_t availableMasks = 0;

    // Размер чанка настоящего расчёта. Замер идёт ровно такими же запусками:
    // на куске поменьше ядро упирается в накладные расходы запуска, и подбор
    // начинает выбирать сетку под них, а не под работу.
    uint64_t chunkSize = 0;
    // Полный объём задачи. Нужен, чтобы отказаться от подбора там, где он
    // не окупается.
    uint64_t totalMasks = 0;

    // Ниже этой оценки времени расчёта подбор не проводится. Замерено: сам он
    // занимает около трети секунды, так что на десятисекундной задаче это уже
    // 3 % против выигрыша до 40 %, а на двухсекундной — почти пятая часть.
    // Ноль отключает проверку; так тесты гоняют подбор на мелких матрицах.
    double minWorthSeconds = 10.0;

    // Сетка из настроек пользователя. Она участвует в замере наравне
    // с остальными, и подбор не имеет права оказаться хуже неё: список
    // кандидатов строится от числа мультипроцессоров и вручную выставленное
    // значение в него может не попасть.
    LaunchGrid userGrid;

    // Печатать таблицу замеров. Нужно, чтобы понимать, почему подбор выбрал
    // то, что выбрал: без неё видно только итог, и отличить плохой поиск от
    // нерепрезентативного замера невозможно.
    bool verbose = false;

    uint64_t*       scratchSpectrum = nullptr;
    const uint64_t* binomTable      = nullptr;
};

// Подбирает число блоков и нитей под конкретную матрицу.
//
// Одного хорошего умолчания нет: оптимум зависит и от ядра, и от ширины
// матрицы, и от числа складываемых строк. Померить дешевле, чем угадать —
// весь подбор занимает доли секунды против часов расчёта.
//
// Возвращает недействительную сетку, если ни один вариант не запустился
// или если задача слишком мелкая, чтобы подбор себя оправдал; вызывающий
// в этом случае должен остаться на настройках пользователя.
LaunchGrid tuneLaunchGrid(const GridTuneTask& task, cudaStream_t stream);
